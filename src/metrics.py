# ============================================================
# 指标集合与优先级
# ============================================================
ALL_METRICS: list[Metric] = [
    METRIC_HALLUCINATION,  # 否决性指标，优先判断
    METRIC_ACCURACY,
    METRIC_HELPFULNESS,
    METRIC_TONE,
    METRIC_PROACTIVE,
]

# 指标优先级（业务方需求排序）
PRIORITY_ORDER = [
    ("M4", "无幻觉", "最高——编造信息直接损害用户权益"),
    ("M1", "准确性", "高——错误信息误导用户操作"),
    ("M2", "有用性", "高——不解决问题的回复无价值"),
    ("M5", "主动服务", "中——影响用户感知但不直接造成损失"),
    ("M3", "语气与共情", "中——影响体验但非核心诉求"),
]


def get_metric_by_id(metric_id: str) -> Metric:
    """按 ID 获取指标定义"""
    for m in ALL_METRICS:
        if m.id == metric_id:
            return m
    raise ValueError(f"Unknown metric id: {metric_id}")


def calculate_weighted_score(scores: Dict[str, int]) -> float:
    """
    根据各指标得分计算加权总分（0-100分制）
    
    -幻觉为否决指标：若 M4=0（存在幻觉），总分上限为50分
    -其余指标按权重加权平均后映射到100分制
    """
    hallucination_pass = scores.get("M4", 1) == 1

    weighted_sum = 0.0
    total_weight = 0.0
    for metric in ALL_METRICS:
        if metric.id == "M4":
            continue
        score = scores.get(metric.id, 3)
        # 1-5 分映射到 0-1
        normalized = (score - 1) / 4
        weighted_sum += normalized * metric.weight
        total_weight += metric.weight

    if total_weight == 0:
        return 0.0

    base_score = (weighted_sum / total_weight) * 100

    # 幻觉否决机制
    if not hallucination_pass:
        base_score = min(base_score, 50.0)

    return round(base_score, 1)
